def test_explain_api_error_cases():
    html = ("<!DOCTYPE HTML PUBLIC \"-//IETF//DTD HTML 2.0//EN\">\n<html><head><title>403 Forbidden"
            "</title></head><body><h1>Forbidden</h1><p>You don't have permission to access "
            "/web_api/login on this server.</p></body></html>")
    err = explain_api_error("login", 403, html.encode("utf-8"), client_ip="10.1.1.50")
    assert err.what == "Login refused by management (HTTP 403)" and err.fix == FORBIDDEN_IP_FIX
    assert err.server_said == "Forbidden You don't have permission to access /web_api/login on this server."
    assert "10.1.1.50" in err.why

    err = explain_api_error("login", 403, {"code": "generic_error", "message": "API is not accessible"})
    assert err.code == "mgmt.forbidden_ip"

    for status in (400, 403):
        body = {"code": "err_login_failed", "message": "Authentication to server failed."}
        err = explain_api_error("login", status, body, domain="Corp")
        assert err.what == "Wrong API key or username/password"
        assert "domain 'Corp'" in err.why
    assert "domain" not in explain_api_error("login", 400, body).why

    err = explain_api_error("login", 429, {"code": "err_too_many_requests",
                                           "message": "Too many requests in a given amount of time"})
    assert err.code == "mgmt.rate_limited"

    err = explain_api_error("add-threat-rule", 409, {
        "code": "generic_err_object_locked",
        "message": "Object 'Standard Threat Prevention' is locked by another session (bob@SmartConsole)"})
    assert err.what == "Objects are locked by another session (bob@SmartConsole)"

    err = explain_api_error("set-threat-profile", 400, {
        "code": "generic_error", "message": "Validation failed with 2 errors",
        "errors": [{"message": "First problem.", "current-session": True}, {"message": "Second."}]})
    assert err.code == "mgmt.validation" and err.server_said == "First problem.\nSecond."
    assert [e["message"] for e in err.errors] == ["First problem.", "Second."]

    err = explain_api_error("show-threat-profile", 404, {"code": "generic_err_object_not_found",
                                                         "message": "Requested object [P1] not found"},
                            payload={"name": "P1"})
    assert err.what == "Object 'P1' was not found (show-threat-profile)"

    err = explain_api_error("add-host", 403, {"code": "generic_err_permission_denied",
                                              "message": "Permission denied"})
    assert err.code == "mgmt.permission_denied" and "Management API Login" in err.fix[0]

    err = explain_api_error("test-ai-guard-api-key", 404, {"code": "generic_err_command_not_found",
                                                           "message": "Unknown command"})
    assert err.what == "This management version does not support test-ai-guard-api-key"

    err = explain_api_error("show-x", 400, {"code": "weird_code", "message": "Something odd"})
    assert err.what == "show-x failed" and err.server_said == "Something odd"
    assert any("log line" in f for f in err.fix)

    err = explain_api_error("publish", 500, {"code": "generic_internal_error", "message": "boom"})
    assert err.code == "mgmt.server_error" and "HTTP 500" in err.what

    err = explain_api_error("login", 502, "<html><body>Bad Gateway</body></html>")
    assert err.code == "mgmt.server_error" and err.server_said == "Bad Gateway"

    d = err.to_dict()
    assert d["code"] == "mgmt.server_error" and d["command"] == "login"


