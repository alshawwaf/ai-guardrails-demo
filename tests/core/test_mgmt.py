def test_login_with_api_key_on_sms(mgmt, pki, runlog):
    srv, client = mgmt()
    key = fake_key()
    info = client.login(api_key=key)
    assert info["server_type"] == "SMS" and client.server_type == "SMS"
    assert info["api_version"] == "2.2" and info["release"] == "R82.20"
    assert info["fingerprint_sha256"] == pki.server_sha256 == client.fingerprint
    assert info["fingerprint_sha1"] == pki.server_sha1
    assert info["read_only"] is False and info["domains"] == [] and info["domain"] is None
    assert info["local_ip"] == "127.0.0.1" and info["reported_port"] == srv.port
    assert "sid" not in info and key not in json.dumps(info)
    assert srv.state.logins == 1
    login = srv.calls_for("login")[0]
    assert login["api-key"] == key
    assert login["session-name"] == "aiguard-demo"
    assert login["session-description"] == "AI Guard Demo Kit"
    assert "domain" not in login and "read-only" not in login
    # the sid is used on the next calls and is masked everywhere
    assert client.sid in sids_seen(srv)
    assert redact.redact("sid is " + client.sid) != "sid is " + client.sid
    cmds = client.commands()
    assert {"add-threat-rule", "install-policy", "test-ai-agent-security-api-key"} <= cmds
    assert client.has("show-logs") and not client.has("frobnicate")
    client.commands()
    assert srv.call_names().count("show-commands") == 1  # cached
    sid = client.sid
    assert_not_logged(runlog, key, sid)
    client.logout()
    assert client.sid is None and srv.state.sessions == {}
    assert_not_logged(runlog, key, sid)


