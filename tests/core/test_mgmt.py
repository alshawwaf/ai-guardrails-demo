def log_text(runlog: RunLog) -> str:
    return (Path(runlog.path).read_text(encoding="utf-8") + "\n"
            + Path(runlog.jsonl_path).read_text(encoding="utf-8"))


def assert_not_logged(runlog: RunLog, *values: str) -> None:
    text = log_text(runlog)
    for v in values:
        assert v and v not in text, "secret leaked into the run log"


def sids_seen(srv) -> set:
    return {h.get("X-chkp-sid") for (_c, _p, h) in srv.calls if h.get("X-chkp-sid")}


