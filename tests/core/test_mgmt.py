def test_timeout_when_server_never_answers(pki, runlog):
    lsock = socket.socket()
    lsock.bind(("127.0.0.1", 0))
    lsock.listen(5)
    accepted = []
    stop = threading.Event()

    def accept():
        lsock.settimeout(0.1)
        while not stop.is_set():
            try:
                conn, _ = lsock.accept()
                accepted.append(conn)  # never answers the TLS handshake
            except OSError:
                continue

    t = threading.Thread(target=accept, daemon=True)
    t.start()
    try:
        client = MgmtClient("127.0.0.1", lsock.getsockname()[1], ca_file=pki.ca_pem_path,
                            log=runlog, timeout=0.5)
        t0 = time.monotonic()
        with pytest.raises(ConnectError) as ei:
            client.login(api_key=fake_key())
        assert ei.value.code == "connect.timeout"
        assert time.monotonic() - t0 < 5
    finally:
        stop.set()
        t.join(2)
        for c in accepted:
            c.close()
        lsock.close()


