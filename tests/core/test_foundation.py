def test_mask_secret_rules():
    assert mask_secret(None) == ""
    assert mask_secret("") == ""
    assert mask_secret("abc") == "****"
    assert mask_secret("abcdefg") == "****"
    tail = rand_alnum(4)
    assert mask_secret("sk-ant-" + rand_alnum(30) + tail) == "sk-ant-****" + tail
    assert mask_secret("sk-" + rand_alnum(30) + tail) == "sk-****" + tail
    assert mask_secret("lk_" + rand_alnum(30) + tail) == "lk_****" + tail
    assert mask_secret("AKIA" + rand_alnum(12, string.ascii_uppercase) + "WXYZ") == "AKIA****WXYZ"
    assert mask_secret("ghp_" + rand_alnum(30) + tail) == "ghp_****" + tail
    assert mask_secret("xoxb-" + rand_alnum(30) + tail) == "xoxb-****" + tail
    hex_key = secrets.token_hex(32)
    assert len(hex_key) == 64
    assert mask_secret(hex_key) == "****" + hex_key[-4:]
    # A short value after a prefix does not reveal most of itself.
    assert mask_secret("sk-abcdefg") == "****defg"
    # Masked values are fixed points.
    for v in ("****", "****abcd", "sk-****abcd", "sk-ant-****abcd", "AKIA****WXYZ"):
        assert mask_secret(v) == v


def test_registered_secret_never_appears_after_redact():
    secret = 'pw"' + rand_alnum(20) + "/&+x"
    register_secret(secret)
    texts = [
        secret,
        "login with %s now" % secret,
        json.dumps({"payload": {"value": secret}}),
        json.dumps({"x": "prefix-%s-suffix" % secret}),
        "https://example.invalid/?q=" + urllib.parse.quote(secret, safe=""),
        "form: " + urllib.parse.quote_plus(secret, safe=""),
        "line1\n%s\nline3" % secret,
    ]
    for text in texts:
        out = do_redact(text)
        assert secret not in out
        assert "****" in out
    obj = {"a": [{"b": secret}], "c": ("x", secret)}
    assert secret not in json.dumps(redact_obj(obj))
    # forget_secret stops masking plain words again
    word = "Harmless" + rand_alnum(6)
    register_secret(word)
    assert word not in do_redact("say %s" % word)
    redact.forget_secret(word)
    assert do_redact("say %s" % word) == "say %s" % word


