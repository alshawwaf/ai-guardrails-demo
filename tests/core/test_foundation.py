def test_runlog_thread_safe_8_threads(aiguard_home):
    log = runlog.RunLog()
    per_thread = 150
    results = {}

    def worker(tid):
        got = []
        for i in range(per_thread):
            if i % 10 == 0:
                got.append((log.info("t%d" % tid, "multi %d" % i, text="a\nb"), tid, i, 2))
            else:
                got.append((log.info("t%d" % tid, "event %d" % i, i=i), tid, i, 1))
        results[tid] = got

    threads = [threading.Thread(target=worker, args=(t,)) for t in range(8)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    log.close()
    all_events = [e for got in results.values() for e in got]
    assert len(all_events) == 8 * per_thread
    starts = sorted(e[0] for e in all_events)
    assert len(set(starts)) == len(starts)
    lines = _read_lines(log.path)
    expected_lines = 1 + sum(e[3] for e in all_events) + 1  # start + events + end
    assert len(lines) == expected_lines
    for line_no, tid, i, width in all_events:
        line = lines[line_no - 1]
        assert HUMAN_RE.match(line), line
        assert (" t%d " % tid) in line and ("multi %d" % i if width == 2 else "event %d" % i) in line
        if width == 2:
            assert lines[line_no] == " " * 30 + "b"
    records = _read_jsonl(log.jsonl_path)
    assert len(records) == 8 * per_thread + 2
    assert [r["line"] for r in records] == sorted(r["line"] for r in records)


