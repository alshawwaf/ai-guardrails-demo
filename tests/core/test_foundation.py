def test_registry_is_thread_safe():
    values = ["Secret%02d-%s" % (i, rand_alnum(12)) for i in range(40)]
    errors_seen = []

    def worker(chunk):
        try:
            for v in chunk:
                register_secret(v)
                assert v not in do_redact("x %s y" % v)
        except AssertionError as exc:  # pragma: no cover - failure path
            errors_seen.append(exc)

    threads = [threading.Thread(target=worker, args=(values[i::8],)) for i in range(8)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    assert not errors_seen
    blob = do_redact(" ".join(values))
    assert not any(v in blob for v in values)


