HUMAN_RE = re.compile(r"^\d\d:\d\d:\d\d\.\d{3} (DEBUG|INFO |WARN |ERROR|HINT )  \S")


def _read_lines(path: Path):
    return path.read_text(encoding="utf-8").split("\n")[:-1]


def _read_jsonl(path: Path):
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]


def test_runlog_files_and_first_line(aiguard_home):
    log = runlog.RunLog()
    try:
        assert log.path.parent == aiguard_home / "logs"
        assert re.match(r"^\d{4}-\d{2}-\d{2}_\d{6}\.log$", log.path.name)
        assert log.jsonl_path == log.path.with_suffix(".jsonl")
        first = _read_lines(log.path)[0]
        assert re.match(r"^\d{4}-\d{2}-\d{2}T\d\d:\d\d:\d\d\S* INFO   session   start "
                        r"host=\S+ user=\S+ ver=1\.0\.0 os=\S", first), first
        rec = _read_jsonl(log.jsonl_path)[0]
        assert rec["line"] == 1 and rec["component"] == "session" and rec["msg"] == "start"
        assert rec["fields"]["ver"] == __version__
        if os.name == "posix":
            assert (log.path.stat().st_mode & 0o777) == 0o600
    finally:
        log.close()


