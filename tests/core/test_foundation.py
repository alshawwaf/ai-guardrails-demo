def test_owned_modules_are_stdlib_only_and_py38_syntax():
    stdlib = set(getattr(sys, "stdlib_module_names", ())) | {"__future__"}
    for name in OWNED_FILES:
        src = (AIGUARD_DIR / name).read_text(encoding="utf-8")
        tree = ast.parse(src, filename=name, feature_version=(3, 8))
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                roots = [a.name.split(".")[0] for a in node.names]
            elif isinstance(node, ast.ImportFrom) and node.level == 0:
                roots = [(node.module or "").split(".")[0]]
            else:
                continue
            for root in roots:
                if stdlib:
                    assert root in stdlib, "%s imports non-stdlib %s" % (name, root)


def test_owned_modules_follow_security_policy():
    forbidden = [
        r"verify\s*=\s*False", r"CERT_NONE", r"check_hostname\s*=\s*False",
        r"_create_unverified_context", r"\beval\s*\(", r"\bexec\s*\(", r"subprocess",
        r"os\.system", r"\bpickle\b", r"shell\s*=\s*True",
    ]
    for name in OWNED_FILES:
        src = (AIGUARD_DIR / name).read_text(encoding="utf-8")
        for pat in forbidden:
            assert not re.search(pat, src), "%s matches forbidden pattern %s" % (name, pat)


