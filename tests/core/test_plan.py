def test_interrupted_script_can_still_be_rolled_back(connect, runlog, state, monkeypatch):
    srv, client = connect()
    plan = build_plan(client, opts(moderation=True), secrets={"lakera_api_key": guard_key()},
                      log=runlog)
    real_wait = client.wait_task

    def wait(task_id, **kw):
        if kw.get("command") == "run-script":
            raise KeyboardInterrupt
        return real_wait(task_id, **kw)

