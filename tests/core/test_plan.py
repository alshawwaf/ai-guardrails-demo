def test_build_plan_is_read_only_and_display_safe(connect, runlog):
    srv, client = connect()
    key = guard_key()
    plan = build_plan(client, opts(moderation=True), secrets={"lakera_api_key": key}, log=runlog)
    assert read_only_calls(srv) == []
    assert "show-package" in srv.call_names() and "show-threat-rule" in srv.call_names()
    assert [(s.id, s.action, s.command) for s in plan.steps] == [
        ("client_host", "add", "add-host"), ("profile", "add", "add-threat-profile"),
        ("rule", "add", "add-threat-rule"), ("publish", "publish", "publish"),
        ("install", "install", "install-policy"), ("moderation", "script", "run-script")]
    assert re.fullmatch(r"[0-9a-f]{12}", plan.plan_id) and plan.plan_id == compute_plan_id(plan)
    assert plan.package == "Standard" and plan.threat_layer == LAYER
    assert plan.protected_scope == HOST and plan.client_host_name == HOST
    assert plan.field_variant == "ai-agent-security" and plan.warnings == []

    prof = plan.step("profile")
    assert prof.payload["ai-agent-security-api-key"] == key            # real value, memory only
    assert prof.display_payload["ai-agent-security-api-key"] == "****" + key[-4:]
    assert prof.display_payload["ai-agent-security"] is True
    assert prof.display_payload["ai-agent-security-settings"] == {"project-id": "proj-demo"}
    assert prof.secret_keys == ["lakera_api_key"] and key not in repr(prof)
    rule = plan.step("rule").display_payload
    assert rule == {"layer": LAYER, "position": "top", "name": "AI Guard Demo", "action": "AIGuard-Demo",
                    "protected-scope": HOST, "track": "Log", "install-on": "HQ-GW", "comments": MARK}
    assert plan.step("moderation").payload["targets"] == ["HQ-GW"]
    assert plan.step("install").payload == {"policy-package": "Standard", "targets": ["HQ-GW"],
                                            "access": False, "threat-prevention": True}

    d = json.dumps(plan.to_dict())
    calls = plan.api_calls()
    assert key not in d and key not in json.dumps(calls) and key not in repr(plan)
    assert [c["command"] for c in calls] == ["add-host", "add-threat-profile", "add-threat-rule",
                                             "publish", "install-policy", "run-script"]
    assert key not in log_text(runlog)

    # stable for identical input, different when any payload changes
    again = build_plan(client, opts(moderation=True), secrets={"lakera_api_key": key}, log=runlog)
    assert again.plan_id == plan.plan_id
    other = build_plan(client, opts(moderation=True, rule_name="Other"), secrets={"lakera_api_key": key},
                       log=runlog)
    assert other.plan_id != plan.plan_id
    other_key = build_plan(client, opts(moderation=True), secrets={"lakera_api_key": guard_key()},
                           log=runlog)
    assert other_key.plan_id != plan.plan_id
    assert build_plan(client, opts(), secrets={"lakera_api_key": key}, log=runlog).plan_id != plan.plan_id
    assert read_only_calls(srv) == []


