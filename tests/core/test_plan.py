def test_owned_modules_stdlib_only_py38_and_no_insecure_calls():
    stdlib = set(getattr(sys, "stdlib_module_names", ())) | {"__future__"}
    banned = re.compile(r"verify\s*=\s*False|CERT_NONE|check_hostname\s*=\s*False|"
                        r"_create_unverified_context|\beval\(|\bexec\(|subprocess|os\.system|pickle")
    for path in (AIGUARD_DIR / "plan.py", AIGUARD_DIR / "templates" / "__init__.py"):
        src = path.read_text(encoding="utf-8")
        tree = ast.parse(src, filename=str(path), feature_version=(3, 8))
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                roots = [a.name.split(".")[0] for a in node.names]
            elif isinstance(node, ast.ImportFrom) and node.level == 0:
                roots = [(node.module or "").split(".")[0]]
            else:
                continue
            for root in roots:
                assert root in stdlib, "%s imports non-stdlib %s" % (path.name, root)
        assert not banned.search(src), path.name


