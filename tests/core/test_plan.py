def test_render_value_substitution_rules():
    v = {"gw": "HQ-GW", "targets": ["m1", "m2"], "on": True, "ai.enable": "ai-agent-security"}
    assert render_value("{targets}", v) == ["m1", "m2"]          # whole string keeps the type
    assert render_value("{on}", v) is True
    assert render_value("on {gw} ({targets})", v) == "on HQ-GW (m1, m2)"
    assert render_value({"{ai.enable}": "{on}"}, v) == {"ai-agent-security": True}
    assert render_value({"literal {braces": "x {y"}, v) == {"literal {braces": "x {y"}
    with pytest.raises(PlanError, match="unknown variable"):
        render_value("{nope}", v)
    key = guard_key()
    real = render_value({"k": "{secret:lakera_api_key}"}, v, {"lakera_api_key": key})
    shown = render_value({"k": "{secret:lakera_api_key}"}, v, {"lakera_api_key": key}, display=True)
    assert real == {"k": key} and shown == {"k": "****" + key[-4:]}
    assert key not in redact.redact("value " + key)              # registered for redaction
    with pytest.raises(PlanError, match="Guard"):
        render_value("{secret:lakera_api_key}", v, {})


