def test_apply_happy_path_with_moderation(connect, runlog, state, aiguard_home):
    srv, client = connect()
    key = guard_key()
    proj = project_id()
    plan = build_plan(client, opts(moderation=True, lakera_project_id=proj),
                      secrets={"lakera_api_key": key}, log=runlog)
    srv.reset_calls()
    events = []
    points_at_publish = []

    def progress(step_id, status, pct, message):
        events.append((step_id, status, pct, message))
        if step_id == "publish" and status == "running" and not points_at_publish:
            points_at_publish.append([(p["status"], len(p["objects"])) for p in state.list_rollbacks()])
            assert not srv.state.published

    result = apply_plan(client, plan, approved_plan_id=plan.plan_id, log=runlog, state=state,
                        progress_cb=progress)
    assert result.ok, result.error and result.error.to_dict()
    assert points_at_publish == [[("recorded", 3)]]   # saved BEFORE publish
    assert result.published and result.installed and result.moderation_enabled is True
    assert re.fullmatch(r"[0-9a-f]{6}", result.rollback_id)
    assert names(srv) == ["add-host", "add-threat-profile", "show-threat-profile", "add-threat-rule",
                          "publish", "install-policy", "run-script"]
    assert [s.status for s in result.steps] == ["done"] * 6
    assert "aiguard rollback %s" % result.rollback_id in result.message

    host = srv.find("host", HOST)
    assert host["ipv4-address"] == CLIENT_IP and host["comments"] == MARK
    prof = srv.find("threat-profile", "AIGuard-Demo")
    assert prof["ai-agent-security"] is True and prof["_secret"] == key
    assert prof["ai-agent-security-settings"] == {"project-id": proj}
    assert prof["threat-emulation"] is False and prof["confidence-level-low"] == "Detect"
    rule = srv.find("threat-rule", "AI Guard Demo")
    assert srv.state.rulebases[LAYER][0] == "AI Guard Demo"
    assert rule["action"]["name"] == "AIGuard-Demo" and rule["protected-scope"][0]["name"] == HOST
    assert rule["install-on"][0]["name"] == "HQ-GW" and rule["track"]["name"] == "Log"
    assert srv.state.published and srv.state.installs[-1] == {
        "policy-package": "Standard", "targets": ["HQ-GW"], "access": False, "threat-prevention": True}
    assert srv.state.moderation == {"HQ-GW": True}
    assert srv.state.scripts[0]["script-type"] == "one time" and CONFP in srv.state.scripts[0]["script"]

    point = state.get_rollback(result.rollback_id)
    assert point["status"] == "installed" and point["plan_id"] == plan.plan_id
    assert point["server"] == "127.0.0.1" and point["gateway"] == "HQ-GW" and point["package"] == "Standard"
    by_step = {o["step"]: o for o in point["objects"]}
    assert by_step["client_host"]["uid"] == host["uid"]
    assert by_step["profile"]["uid"] == prof["uid"] and by_step["rule"]["uid"] == rule["uid"]
    assert by_step["rule"]["rollback"] == {"command": "delete-threat-rule",
                                          "payload": {"layer": LAYER, "name": "AI Guard Demo"}}
    assert by_step["moderation"]["rollback"]["command"] == "run-script"
    assert "-v false" in by_step["moderation"]["rollback"]["payload"]["script"]

